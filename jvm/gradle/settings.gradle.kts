// Writes `ViewSettings.java` and `ViewSounds.java`, plain-Java classes of the shared settings schema and sound rule
// table (core-view/settings/settings.json and sounds.json), into the applying module's own package, as tokens.gradle.kts
// does for the tokens. The website's copies come from tools/settings/generate.mjs; neither toolchain runs the other.
//
// ViewSettings has one block of constants per setting the mod has (those with a "mod" entry), resolved for the mod:
//   NAME_KEY      the key the mod stores it under
//   NAME_DEFAULT  the default (a choice's is its index in NAME_IDS; a set's a String[])
//   NAME_MIN, NAME_MAX, NAME_STEP   an int's range
//   NAME_IDS, NAME_LABELS, NAME_VALUES   a choice's ids, the labels the panel shows, and its numbers when it has them
// ViewSounds carries the engine constants, the sound ids the mod has, the ladders and the named pitches.
//
// The applying module sets, before applying this script:
//   extra["settingsPackage"] = "com.gtnhplanner.core.view"

import groovy.json.JsonSlurper

abstract class GenerateViewSettings : DefaultTask() {
    @get:InputFile
    abstract val settings: RegularFileProperty

    @get:InputFile
    abstract val sounds: RegularFileProperty

    @get:Input
    abstract val pkg: Property<String>

    @get:OutputDirectory
    abstract val out: DirectoryProperty

    private fun upper(name: String) = name.replace(Regex("([a-z0-9])([A-Z])"), "$1_$2").uppercase()

    /** A value that differs by host is {web, mod}; anything else is the same on both. */
    private fun forMod(v: Any?): Any? =
        if (v is Map<*, *> && (v.containsKey("web") || v.containsKey("mod"))) v["mod"] else v

    private fun num(n: Any?, asDouble: Boolean): String {
        val text = n.toString()
        return if (asDouble && !text.contains('.') && !text.contains('E')) "$text.0" else text
    }

    private fun str(s: Any?) = "\"" + s.toString().replace("\\", "\\\\").replace("\"", "\\\"") + "\""

    private fun strings(list: List<*>) = list.joinToString(", ") { str(it) }

    private fun numbers(list: List<*>): String {
        val doubles = list.any { it.toString().contains('.') }
        val type = if (doubles) "double" else "int"
        return "$type[] = { ${list.joinToString(", ") { num(it, doubles) }} }"
    }

    @TaskAction
    fun generate() {
        @Suppress("UNCHECKED_CAST")
        val root = JsonSlurper().parse(settings.get().asFile) as Map<String, Any?>
        @Suppress("UNCHECKED_CAST")
        val table = JsonSlurper().parse(sounds.get().asFile) as Map<String, Any?>
        val sb = StringBuilder()
        sb.append("// Generated by jvm/gradle/settings.gradle.kts from core-view/settings/settings.json. Do not edit.\n")
        sb.append("package ${pkg.get()};\n\n")
        sb.append("public final class ViewSettings {\n    private ViewSettings() {}\n")

        @Suppress("UNCHECKED_CAST")
        val all = root["settings"] as Map<String, Map<String, Any?>>
        for ((name, spec) in all) {
            @Suppress("UNCHECKED_CAST")
            val mod = spec["mod"] as Map<String, Any?>? ?: continue
            val n = upper(name)
            sb.append("\n    // ${name}\n")
            sb.append("    public static final String ${n}_KEY = ${str(mod["key"])};\n")
            val default = forMod(spec["default"])
            when (spec["type"]) {
                "bool" -> sb.append("    public static final boolean ${n}_DEFAULT = $default;\n")
                "int" -> {
                    sb.append("    public static final int ${n}_DEFAULT = $default;\n")
                    for (f in listOf("min", "max", "step")) {
                        val v = forMod(spec[f]) ?: continue
                        sb.append("    public static final int ${n}_${f.uppercase()} = $v;\n")
                    }
                }
                "text" -> sb.append("    public static final String ${n}_DEFAULT = ${str(default)};\n")
                "set" -> {
                    sb.append("    public static final String[] ${n}_DEFAULT = { ${strings(default as List<*>)} };\n")
                    val of = spec["of"] as List<*>?
                    if (of != null) sb.append("    public static final String[] ${n}_OF = { ${strings(of)} };\n")
                }
                "choice" -> {
                    val ids = spec["ids"] as List<*>
                    val index = ids.indexOf(default)
                    if (index < 0) throw GradleException("settings: $name default $default is not one of $ids")
                    sb.append("    public static final int ${n}_DEFAULT = $index;\n")
                    sb.append("    public static final String[] ${n}_IDS = { ${strings(ids)} };\n")
                    sb.append("    public static final String[] ${n}_LABELS = { ${strings(spec["labels"] as List<*>)} };\n")
                    val values = forMod(spec["values"])
                    if (values is List<*>) sb.append("    public static final ${numbers(values).replaceFirst("[] =", "[] ${n}_VALUES =")};\n")
                }
                else -> throw GradleException("settings: $name has type ${spec["type"]}")
            }
        }
        sb.append("}\n")

        val dir = out.get().asFile.resolve(pkg.get().replace('.', '/'))
        dir.mkdirs()
        dir.resolve("ViewSettings.java").writeText(sb.toString())

        val so = StringBuilder()
        so.append("// Generated by jvm/gradle/settings.gradle.kts from core-view/settings/sounds.json. Do not edit.\n")
        so.append("package ${pkg.get()};\n\n")
        so.append("public final class ViewSounds {\n    private ViewSounds() {}\n\n")
        @Suppress("UNCHECKED_CAST")
        val engine = table["engine"] as Map<String, Any?>
        for ((k, v) in engine) {
            val n = upper(k)
            if (v is List<*>) so.append("    public static final ${numbers(v).replaceFirst("[] =", "[] $n =")};\n")
            else {
                val type = if (v.toString().contains('.')) "double" else "int"
                so.append("    public static final $type $n = ${num(v, false)};\n")
            }
        }
        @Suppress("UNCHECKED_CAST")
        val sounds = table["sounds"] as List<Map<String, Any?>>
        val modIds = sounds.filter { (it["hosts"] as List<*>).contains("mod") }.map { it["id"] }
        so.append("\n    /** Every sound id the mod has, in sounds.json's order. */\n")
        so.append("    public static final String[] IDS = { ${strings(modIds)} };\n")
        @Suppress("UNCHECKED_CAST")
        val ladders = table["ladders"] as Map<String, Map<String, Any?>>
        for ((k, ladder) in ladders) {
            val n = upper(k)
            so.append("\n    /** ${ladder["about"]} */\n")
            so.append("    public static final String ${n}_LADDER_SOUND = ${str(ladder["sound"])};\n")
            so.append("    public static final double ${n}_LADDER_BASE = ${num(ladder["base"], true)};\n")
            so.append("    public static final double ${n}_LADDER_RATIO = ${num(ladder["ratio"], true)};\n")
        }
        so.append("\n")
        @Suppress("UNCHECKED_CAST")
        val pitches = table["pitches"] as Map<String, Any?>
        for ((k, v) in pitches) so.append("    public static final double ${upper(k)} = ${num(v, true)};\n")
        so.append("}\n")
        dir.resolve("ViewSounds.java").writeText(so.toString())
    }
}

val settingsDir = rootProject.file("core/core-view/settings")
val settingsPackage = extra["settingsPackage"] as String
val generateViewSettings = tasks.register<GenerateViewSettings>("generateViewSettings") {
    settings.set(File(settingsDir, "settings.json"))
    sounds.set(File(settingsDir, "sounds.json"))
    pkg.set(settingsPackage)
    out.set(layout.buildDirectory.dir("generated/settings/java"))
}

extensions.getByType<JavaPluginExtension>().sourceSets.getByName("main").java.srcDir(generateViewSettings.flatMap { it.out })

// Writes `Tokens.java`, a plain-Java class of the shared view tokens (core-view/tokens/tokens.json), into the applying
// module's own package, so a module that sits above core-view in the build order still gets the values it draws with
// without depending on it. The website's copies come from tools/tokens/generate.mjs; neither toolchain runs the other,
// and both are held to tokens/mixes.expected.json for every colour mix, so a mix has the same bytes on both sides.
//
// The applying module sets, before applying this script:
//   extra["tokensPackage"] = "com.gtnhplanner.core.layout"
//   extra["tokensGroups"]  = listOf("grid", "wire", "size")     // optional; every group when left out
// Groups are the keys of tokens.json: colours (palette, tone, tile, in, out, foot), tiers, kindMixes, pulse and the
// geometry groups (grid, wire, size, card, drawer).

import groovy.json.JsonSlurper

abstract class GenerateTokens : DefaultTask() {
    @get:InputFile
    abstract val tokens: RegularFileProperty

    @get:InputFile
    abstract val expected: RegularFileProperty

    @get:Input
    abstract val pkg: Property<String>

    @get:Input
    abstract val groups: ListProperty<String>

    @get:OutputDirectory
    abstract val out: DirectoryProperty

    private fun upper(name: String) = name.replace(Regex("([a-z0-9])([A-Z])"), "$1_$2").uppercase()

    private fun cap(name: String) = name.substring(0, 1).uppercase() + name.substring(1)

    private fun hex(s: String) = "0xFF" + s.removePrefix("#").uppercase()

    private fun number(n: Any?, asDouble: Boolean): String {
        val text = n.toString()
        return if (asDouble && !text.contains('.') && !text.contains('E')) "$text.0" else text
    }

    private fun mix(a: String, b: String, shareText: String): String {
        fun channel(c: String, shift: Int) = c.removePrefix("#").toInt(16) shr shift and 0xFF
        val s = Math.max(0f, Math.min(1f, shareText.toFloat()))
        var rgb = 0
        for (shift in intArrayOf(16, 8, 0)) {
            val v = Math.round(channel(a, shift) * s + channel(b, shift) * (1 - s))
            rgb = rgb or (v shl shift)
        }
        return "#%06X".format(rgb)
    }

    @TaskAction
    fun generate() {
        @Suppress("UNCHECKED_CAST")
        val root = JsonSlurper().parse(tokens.get().asFile) as Map<String, Any?>
        @Suppress("UNCHECKED_CAST")
        val expectedMixes = JsonSlurper().parse(expected.get().asFile) as Map<String, String>
        val want = groups.get().toSet()
        fun wanted(g: String) = want.isEmpty() || g in want

        val sb = StringBuilder()
        sb.append("// Generated by jvm/gradle/tokens.gradle.kts from core-view/tokens/tokens.json. Do not edit.\n")
        sb.append("package ${pkg.get()};\n\n")
        sb.append("public final class Tokens {\n    private Tokens() {}\n")

        @Suppress("UNCHECKED_CAST")
        val colors = root["colors"] as Map<String, Map<String, String>>
        for ((group, entries) in colors) {
            if (!wanted(group)) continue
            sb.append("\n    public static final class ${cap(group)} {\n        private ${cap(group)}() {}\n")
            for ((name, value) in entries) sb.append("        public static final int ${upper(name)} = ${hex(value)};\n")
            sb.append("    }\n")
        }

        if (wanted("tiers")) {
            @Suppress("UNCHECKED_CAST")
            val tiers = root["tiers"] as List<Map<String, Any?>>
            sb.append("\n    public static final class Tiers {\n        private Tiers() {}\n")
            sb.append("        /** background, border and text are 0xAARRGGBB. */\n")
            sb.append("        public record Tier(String name, int background, int border, int text, boolean underline) {}\n\n")
            sb.append("        public static final Tier[] ALL = {\n")
            for (t in tiers) {
                sb.append(
                    "            new Tier(\"${t["name"]}\", ${hex(t["background"] as String)}, ${hex(t["border"] as String)}, " +
                        "${hex(t["text"] as String)}, ${t["underline"]}),\n",
                )
            }
            sb.append("        };\n    }\n")
        }

        @Suppress("UNCHECKED_CAST")
        val kindMixes = root["kindMixes"] as Map<String, Any?>
        if (wanted("kindMixes")) {
            @Suppress("UNCHECKED_CAST")
            val kinds = kindMixes["kinds"] as Map<String, String>
            @Suppress("UNCHECKED_CAST")
            val mixes = kindMixes["mixes"] as Map<String, Map<String, Any?>>
            val palette = colors["palette"]!!
            sb.append("\n    /** Each kind's colour mixed into a palette colour, computed in float32 as the mod's Hyb.mix does. */\n")
            sb.append("    public static final class KindMixes {\n        private KindMixes() {}\n")
            for ((kind, colorName) in kinds) {
                val tint = palette[colorName]!!
                sb.append("        public static final int ${upper(kind)}_TINT = ${hex(tint)};\n")
                for ((name, m) in mixes) {
                    val value = mix(tint, palette[m["over"] as String]!!, m["share"].toString())
                    val key = "$kind.$name"
                    if (expectedMixes[key] != value) {
                        throw GradleException("tokens: mix $key is $value but mixes.expected.json says ${expectedMixes[key]}")
                    }
                    sb.append("        public static final int ${upper(kind)}_${upper(name)} = ${hex(value)};\n")
                }
            }
            sb.append("    }\n")
        }

        if (wanted("pulse")) {
            @Suppress("UNCHECKED_CAST")
            val pulse = root["pulse"] as Map<String, Any?>
            sb.append("\n    /** Pulse periods in seconds. */\n    public static final class Pulse {\n        private Pulse() {}\n")
            for ((name, v) in pulse) sb.append("        public static final double $name = ${number(v, true)};\n")
            sb.append("    }\n")
        }

        @Suppress("UNCHECKED_CAST")
        val geometry = root["geometry"] as Map<String, Map<String, Any?>>
        for ((group, entries) in geometry) {
            if (!wanted(group)) continue
            sb.append("\n    public static final class ${cap(group)} {\n        private ${cap(group)}() {}\n")
            for ((name, spec) in entries) {
                if (spec is Map<*, *>) {
                    for (host in listOf("web", "mod")) {
                        val v = spec[host] ?: continue
                        sb.append("        public static final ${scalarType(v)} ${name}_${host.uppercase()} = ${number(v, false)};\n")
                    }
                } else if (spec is List<*>) {
                    val doubles = spec.any { it.toString().contains('.') }
                    val type = if (doubles) "double" else "int"
                    sb.append("        public static final $type[] $name = { ${spec.joinToString(", ") { number(it, doubles) }} };\n")
                } else {
                    sb.append("        public static final ${scalarType(spec)} $name = ${number(spec, false)};\n")
                }
            }
            sb.append("    }\n")
        }
        sb.append("}\n")

        val dir = out.get().asFile.resolve(pkg.get().replace('.', '/'))
        dir.mkdirs()
        dir.resolve("Tokens.java").writeText(sb.toString())
    }

    private fun scalarType(v: Any?) = if (v.toString().contains('.')) "double" else "int"
}

val tokensDir = rootProject.file("core/core-view/tokens")
// Read the applying module's settings here: inside the task block, `extra` is the task's own.
val tokensPackage = extra["tokensPackage"] as String

@Suppress("UNCHECKED_CAST")
val tokensGroups = (if (extra.has("tokensGroups")) extra["tokensGroups"] as List<String> else emptyList())
val generateTokens = tasks.register<GenerateTokens>("generateTokens") {
    tokens.set(File(tokensDir, "tokens.json"))
    expected.set(File(tokensDir, "mixes.expected.json"))
    pkg.set(tokensPackage)
    groups.set(tokensGroups)
    out.set(layout.buildDirectory.dir("generated/tokens/java"))
}

extensions.getByType<JavaPluginExtension>().sourceSets.getByName("main").java.srcDir(generateTokens.flatMap { it.out })

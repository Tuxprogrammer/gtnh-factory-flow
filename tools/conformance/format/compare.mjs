#!/usr/bin/env node
// Builds conformance/format/COMPARISON.md: the website's number formatters against the mod's, on the one value list in
// conformance/format/values.json. The three answer files it reads are each pinned by a test (website-out.json by
// src/test-support/format-conformance.test.ts, mod-out.json by core-view FmtConformanceTest, mod-recipe-overlay-out.json
// by the mod's RecipeOverlayFormatTest), so the table cannot drift from the code.
//
//   node tools/conformance/format/compare.mjs            rewrite COMPARISON.md
//   node tools/conformance/format/compare.mjs --check    exit 1 when COMPARISON.md is not what the answer files make
//
// The formatters are not meant to agree; the table says where they do not. Plain Node, no dependencies.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const DIR = fileURLToPath(new URL("../../../conformance/format/", import.meta.url));

const readJson = (name) => JSON.parse(readFileSync(path.join(DIR, name), "utf8"));

/** The inputs of a row, in order: its groups one after another. */
export function inputsOf(values, row) {
  return row.inputs.flatMap((g) => {
    if (!values.groups[g]) throw new Error(`row ${row.id} names no group ${g}`);
    return values.groups[g];
  });
}

/** How an input reads in the table. */
export function show(input) {
  if (Array.isArray(input)) return `${input[0]} EU/t over ${input[1]}/s`;
  return String(input);
}

const cell = (s) => `\`${String(s).replace(/\|/g, "\\|")}\``;

/** Which answer file holds the mod's answer for a row, or null when the mod has no such formatter. */
function modFile(row) {
  if (!row.mod) return null;
  return row.mod.startsWith("Fmt.") ? "mod-out.json" : "mod-recipe-overlay-out.json";
}

/** The comparison, as Markdown text, from the parsed files. */
export function buildComparison(values, web, mods) {
  const out = [];
  const summary = [];
  const sections = [];
  for (const row of values.rows) {
    const inputs = inputsOf(values, row);
    const w = web.rows[row.id];
    if (!w || w.length !== inputs.length) throw new Error(`website-out.json has no ${inputs.length} answers for ${row.id}`);
    const file = modFile(row);
    const m = file ? mods[file].rows[row.id] : null;
    if (file && (!m || m.length !== inputs.length)) throw new Error(`${file} has no ${inputs.length} answers for ${row.id}`);

    const lines = [`### ${row.id}`, "", `${row.what}. Website: ${row.web}. Mod: ${row.mod ?? "none"}.`, ""];
    if (!m) {
      summary.push(`| ${row.id} | ${row.web} | none | ${inputs.length} | | |`);
      lines.push("The mod has no formatter for this; the website's answers:", "", "| input | website |", "| --- | --- |");
      inputs.forEach((x, i) => lines.push(`| ${cell(show(x))} | ${cell(w[i])} |`));
    } else {
      const differ = inputs.map((x, i) => i).filter((i) => w[i] !== m[i]);
      summary.push(`| ${row.id} | ${row.web} | ${row.mod} | ${inputs.length} | ${inputs.length - differ.length} | ${differ.length} |`);
      if (differ.length === 0) {
        lines.push(`The two agree on all ${inputs.length} inputs.`);
      } else {
        lines.push(`The two agree on ${inputs.length - differ.length} of ${inputs.length} inputs and differ on these:`, "");
        lines.push("| input | website | mod |", "| --- | --- | --- |");
        for (const i of differ) lines.push(`| ${cell(show(inputs[i]))} | ${cell(w[i])} | ${cell(m[i])} |`);
        const same = inputs.filter((x, i) => !differ.includes(i)).map(show);
        if (same.length > 0) lines.push("", `Same on: ${same.join(", ")}.`);
      }
    }
    sections.push(lines.join("\n"));
  }
  out.push(
    "# Website formatters against the mod's",
    "",
    "Generated by `tools/conformance/format/compare.mjs` from `values.json`, `website-out.json`, `mod-out.json` and `mod-recipe-overlay-out.json`; do not edit. `README.md` beside it says what each difference means and what to decide.",
    "",
    "A cell is the exact text the formatter returns; `throws X` is an exception the formatter raises. `Fmt` is `jvm/core/core-view` `Fmt.java`; `GuiHelper` is the mod's recipe overlay.",
    "",
    "| row | website | mod | inputs | same | differ |",
    "| --- | --- | --- | --- | --- | --- |",
    ...summary,
    "",
    "## Rows",
    "",
    sections.join("\n\n"),
    "",
  );
  return out.join("\n");
}

export function load() {
  const values = readJson("values.json");
  const web = readJson("website-out.json");
  const mods = { "mod-out.json": readJson("mod-out.json"), "mod-recipe-overlay-out.json": readJson("mod-recipe-overlay-out.json") };
  return buildComparison(values, web, mods);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const text = load();
  const target = path.join(DIR, "COMPARISON.md");
  if (process.argv.includes("--check")) {
    let have = "";
    try {
      have = readFileSync(target, "utf8");
    } catch {
      // missing counts as different
    }
    if (have !== text) {
      console.error("conformance/format/COMPARISON.md is out of date: run node tools/conformance/format/compare.mjs");
      process.exit(1);
    }
  } else {
    writeFileSync(target, text);
    console.log(`wrote ${path.relative(process.cwd(), target)}`);
  }
}

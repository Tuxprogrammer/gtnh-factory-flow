#!/usr/bin/env node
// Writes the website's copies of the shared settings schema and sound rule table
// (jvm/core/core-view/settings/settings.json and sounds.json):
//   src/lib/view-settings.generated.ts   every setting the website has, its host-resolved defaults, ranges and choices
//   src/lib/view-sounds.generated.ts     the sound engine constants, the sound ids, the ladders and the event table
// Both are gitignored: tools/tokens/generate.mjs calls run() on every build, so the npm pre-hooks and the vitest
// global setup produce them with the tokens. The Java side writes its own classes from the same JSON
// (jvm/gradle/settings.gradle.kts); neither toolchain runs the other.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const settingsDir = path.join(root, "jvm", "core", "core-view", "settings");
const outDir = path.join(root, "src", "lib");

const readJson = (name) => JSON.parse(fs.readFileSync(path.join(settingsDir, name), "utf8"));

/** A value that differs by host is `{ web, mod }`; anything else is the same on both. */
function isHostSplit(v) {
  return v !== null && typeof v === "object" && !Array.isArray(v) && ("web" in v || "mod" in v);
}

export function forHost(v, host) {
  return isHostSplit(v) ? v[host] : v;
}

const FIELDS = ["type", "label", "unit", "min", "max", "step", "ids", "labels", "values", "default", "of", "scope", "parity", "display", "base", "phoneBase"];

/** One setting as a host sees it: its shared fields resolved for the host, plus where that host keeps it. */
export function resolveSetting(spec, host) {
  const own = spec[host];
  if (!own) return undefined;
  const out = {};
  for (const f of FIELDS) {
    if (!(f in spec)) continue;
    const v = forHost(spec[f], host);
    if (v !== undefined) out[f] = v;
  }
  if (own.key !== undefined) out.key = own.key;
  if (own.field !== undefined) out.field = own.field;
  if (own.divisor !== undefined) out.divisor = own.divisor;
  if (spec.type === "choice") out.defaultIndex = spec.ids.indexOf(out.default);
  return out;
}

export function buildFiles(settings, sounds) {
  const web = {};
  for (const [name, spec] of Object.entries(settings.settings)) {
    const s = resolveSetting(spec, "web");
    if (s) web[name] = s;
  }
  const ts = [
    "// Generated by tools/settings/generate.mjs from jvm/core/core-view/settings/settings.json. Do not edit.",
    "",
    `export const VIEW_SETTINGS = ${JSON.stringify(web, null, 2)} as const;`,
    "",
    "export type ViewSettingName = keyof typeof VIEW_SETTINGS;",
    "",
  ].join("\n");
  const list = sounds.sounds;
  const table = {
    engine: sounds.engine,
    webEngine: sounds.webEngine,
    ids: list.filter((s) => s.hosts.includes("web")).map((s) => s.id),
    ladders: sounds.ladders,
    pitches: sounds.pitches,
    events: sounds.events.filter((e) => !e.hosts || e.hosts.includes("web")).map(({ mod: _mod, ...e }) => e),
    gatedBy: sounds.gatedBy,
  };
  const tsSounds = [
    "// Generated by tools/settings/generate.mjs from jvm/core/core-view/settings/sounds.json. Do not edit.",
    "",
    `export const VIEW_SOUNDS = ${JSON.stringify(table, null, 2)} as const;`,
    "",
  ].join("\n");
  return { settings: ts, sounds: tsSounds };
}

function writeIfChanged(file, text) {
  if (fs.existsSync(file) && fs.readFileSync(file, "utf8") === text) return;
  fs.writeFileSync(file, text);
}

export function run() {
  const files = buildFiles(readJson("settings.json"), readJson("sounds.json"));
  writeIfChanged(path.join(outDir, "view-settings.generated.ts"), files.settings);
  writeIfChanged(path.join(outDir, "view-sounds.generated.ts"), files.sounds);
}

if (process.argv[1] && fs.realpathSync(process.argv[1]) === fs.realpathSync(fileURLToPath(import.meta.url))) {
  try {
    run();
  } catch (e) {
    console.error(String(e.message ?? e));
    process.exit(1);
  }
}

#!/usr/bin/env node
// Writes the website's copies of the shared view tokens (jvm/core/core-view/tokens/tokens.json):
//   src/components/flow/clean/tokens.generated.ts   values for TypeScript
//   src/components/flow/clean/tokens.generated.css  the same colours as --cc-* custom properties
// Both are gitignored: every build that needs them runs this first (npm pre-hooks and the vitest global setup).
// The Java side writes its own class from the same JSON (jvm/gradle/tokens.gradle.kts); neither toolchain runs the other.
//
// Mixes are computed here in float32 with half-up rounding, as Java's Hyb.mix does, and compared with
// tokens/mixes.expected.json, which the Java generator is held to as well. `--accept` rewrites that file.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const tokensDir = path.join(root, "jvm", "core", "core-view", "tokens");
const outDir = path.join(root, "src", "components", "flow", "clean");

/** `a` mixed into `b`, `share` of a, per channel in float32, rounded half up (Java's Math.round(float)). */
export function mixHexF32(a, b, share) {
  const ch = (hex) => {
    const v = Number.parseInt(hex.slice(1), 16);
    return [(v >> 16) & 255, (v >> 8) & 255, v & 255];
  };
  const ca = ch(a);
  const cb = ch(b);
  const s = Math.fround(Math.max(0, Math.min(1, share)));
  const rest = Math.fround(1 - s);
  const out = [0, 1, 2].map((i) =>
    Math.floor(Math.fround(Math.fround(ca[i] * s) + Math.fround(cb[i] * rest)) + 0.5),
  );
  return `#${out.map((c) => c.toString(16).padStart(2, "0")).join("").toUpperCase()}`;
}

const kebab = (s) => s.replace(/([A-Z])/g, "-$1").toLowerCase();

/** The expected-mix key for a mix of a kind: `source.edge`. */
function kindMixTable(tokens) {
  const { kinds, mixes } = tokens.kindMixes;
  const palette = tokens.colors.palette;
  const table = {};
  for (const [kind, colorName] of Object.entries(kinds)) {
    for (const [name, mix] of Object.entries(mixes)) {
      table[`${kind}.${name}`] = mixHexF32(palette[colorName], palette[mix.over], mix.share);
    }
  }
  return table;
}

export function readTokens() {
  return JSON.parse(fs.readFileSync(path.join(tokensDir, "tokens.json"), "utf8"));
}

function hostValues(spec) {
  // number | number[] | { web?, mod? }
  if (typeof spec === "number" || Array.isArray(spec)) return { shared: spec };
  return { web: spec.web, mod: spec.mod };
}

export function buildFiles(tokens, expected, accept) {
  const mixes = kindMixTable(tokens);
  if (accept) expected = mixes;
  const wrong = Object.keys(mixes).filter((k) => expected[k] !== mixes[k]);
  const stale = Object.keys(expected).filter((k) => !(k in mixes));
  if (wrong.length || stale.length) {
    throw new Error(
      `tokens: mixes differ from mixes.expected.json (${[...wrong, ...stale].join(", ")}); ` +
        "check the change, then run `node tools/tokens/generate.mjs --accept`",
    );
  }

  const ts = [];
  ts.push("// Generated by tools/tokens/generate.mjs from jvm/core/core-view/tokens/tokens.json. Do not edit; not committed.");
  ts.push("");
  ts.push(`export const TOKEN_COLORS = ${JSON.stringify(tokens.colors, null, 2)} as const;`);
  ts.push("");
  ts.push(`export const TOKEN_TIERS = ${JSON.stringify(tokens.tiers, null, 2)} as const;`);
  ts.push("");
  const mixTable = {};
  for (const key of Object.keys(mixes)) {
    const [kind, name] = key.split(".");
    (mixTable[kind] ??= {})[name] = mixes[key];
  }
  for (const [kind, colorName] of Object.entries(tokens.kindMixes.kinds)) {
    mixTable[kind].tint = tokens.colors.palette[colorName];
  }
  ts.push(`export const TOKEN_KIND_MIXES = ${JSON.stringify(mixTable, null, 2)} as const;`);
  ts.push("");
  ts.push(`export const TOKEN_PULSE = ${JSON.stringify(tokens.pulse, null, 2)} as const;`);
  ts.push("");
  // Geometry: a value both hosts share is NAME; one that differs by host is NAME_WEB / NAME_MOD.
  const geometry = {};
  for (const [group, entries] of Object.entries(tokens.geometry)) {
    geometry[group] = {};
    for (const [name, spec] of Object.entries(entries)) {
      const v = hostValues(spec);
      if ("shared" in v) geometry[group][name] = v.shared;
      else {
        if (v.web !== undefined) geometry[group][`${name}_WEB`] = v.web;
        if (v.mod !== undefined) geometry[group][`${name}_MOD`] = v.mod;
      }
    }
  }
  ts.push(`export const TOKEN_GEOMETRY = ${JSON.stringify(geometry, null, 2)} as const;`);
  ts.push("");

  const css = [];
  css.push("/* Generated by tools/tokens/generate.mjs from jvm/core/core-view/tokens/tokens.json. Do not edit; not committed. */");
  css.push(":root,\n.cc {");
  for (const [name, hex] of Object.entries(tokens.colors.palette)) css.push(`  --cc-${kebab(name)}: ${hex.toLowerCase()};`);
  // The sets are --cc-set-<group>-<name>: clean.css assigns its own --cc-tile-* per row state from them.
  for (const group of ["tone", "tile", "in", "out", "foot"]) {
    const prefix = group === "tone" ? "tone" : `set-${group}`;
    for (const [name, hex] of Object.entries(tokens.colors[group])) {
      css.push(`  --cc-${prefix}-${kebab(name)}: ${hex.toLowerCase()};`);
    }
  }
  for (const [name, seconds] of Object.entries(tokens.pulse)) {
    const var_ = name === "GLOW" ? "pulse" : name === "ACCEPT" ? "accept-pulse" : "prompt";
    css.push(`  --cc-${var_}: ${seconds}s;`);
  }
  css.push("}");
  css.push("");
  return { ts: ts.join("\n"), css: css.join("\n"), mixes };
}

function writeIfChanged(file, text) {
  if (fs.existsSync(file) && fs.readFileSync(file, "utf8") === text) return;
  fs.writeFileSync(file, text);
}

export function run(accept = false) {
  const tokens = readTokens();
  const expectedFile = path.join(tokensDir, "mixes.expected.json");
  const expected = fs.existsSync(expectedFile) ? JSON.parse(fs.readFileSync(expectedFile, "utf8")) : {};
  const { ts, css, mixes } = buildFiles(tokens, expected, accept);
  if (accept) fs.writeFileSync(expectedFile, `${JSON.stringify(mixes, null, 2)}\n`);
  writeIfChanged(path.join(outDir, "tokens.generated.ts"), `${ts}`);
  writeIfChanged(path.join(outDir, "tokens.generated.css"), css);
}

if (process.argv[1] && fs.realpathSync(process.argv[1]) === fs.realpathSync(fileURLToPath(import.meta.url))) {
  try {
    run(process.argv.includes("--accept"));
  } catch (e) {
    console.error(String(e.message ?? e));
    process.exit(1);
  }
}

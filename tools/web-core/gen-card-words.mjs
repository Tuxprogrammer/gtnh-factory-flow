// Writes src/lib/core/card-words.generated.ts: the recipe card's words (core-base Text keys `gtnhplanner.card.*`) from
// the mod's language file, which is where the core's words live. The website hands them to the compiled core once per
// loaded core (`ViewExports.viewCardWords`, src/components/flow/clean/card-view.ts). Gitignored; gen-types.mjs runs this
// on every run, so every build, typecheck and test run has it.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { LANG_FILE, cardWords } from "./view.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
export const OUTPUT = path.join(root, "src", "lib", "core", "card-words.generated.ts");

export function generate() {
  const words = cardWords();
  const sorted = Object.fromEntries(
    Object.keys(words)
      .sort()
      .map((k) => [k, words[k]]),
  );
  return (
    `// Generated by tools/web-core/gen-card-words.mjs from ${LANG_FILE} (do not edit; gitignored).\n` +
    `// The recipe card's words, key to pattern, as the compiled core's Text reads them.\n` +
    `export const CARD_WORDS: Readonly<Record<string, string>> = ${JSON.stringify(sorted, null, 2)};\n`
  );
}

/** Writes the file when it differs; returns whether it changed. */
export function run() {
  const text = generate();
  const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, "utf8") : null;
  if (current === text) return false;
  fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
  fs.writeFileSync(OUTPUT, text);
  return true;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (run()) console.log(`wrote ${path.relative(root, OUTPUT)}`);
}
